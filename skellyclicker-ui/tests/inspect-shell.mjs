import {chromium, expect} from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({headless:true,channel:process.env.SKELLYCLICKER_BROWSER_CHANNEL || "msedge"});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
const failures=[];
page.on('response', r=>{if(r.status()>=400) failures.push({status:r.status(),url:r.url()});});
page.on('pageerror', error=>errors.push(error.stack || String(error)));
page.on('console', message=>{if(message.type()==='error') errors.push(message.text());});
await page.goto(process.env.SKELLYCLICKER_TEST_UI_URL || 'http://127.0.0.1:5176');
await expect(page.getByText('Backend connected', {exact:true})).toBeVisible();
await expect(page.getByRole('img', {name:'SkellyClicker', exact:true})).toBeVisible();
await expect.poll(()=>page.workers().length).toBeGreaterThan(0);
await page.evaluate(()=>document.fonts.ready);
await expect(page.locator('canvas').first()).toBeVisible();
assert.equal(await page.getByText('Streaming', {exact:true}).count(),0);
console.log(JSON.stringify({title:await page.title(),body:await page.locator('body').innerText(),errors,failures,workers:page.workers().map(w=>w.url())},null,2));
await page.screenshot({path:'../.test-artifacts/playback-shell.png',fullPage:true});
await browser.close();
assert.deepEqual(errors,[]);
assert.deepEqual(failures,[]);
